# (дугаAB+дугаCD)/2=60 => дугаAB+дугаCD=120°. AB=2R sin(дугаAB/2)... комбинируем.
# R = sqrt(p^2+q^2+pq)/sqrt(3)? Проверим моделью.
# ══════════════════════════════════════════════════════════════════════════
def s14(p, q):
    # угол AKB между хордами AC,BD =60 => полусумма дуг AB и CD =60 => arcAB+arcCD=120.
    # p=AB=2R sin(arcAB/2), q=CD=2R sin(arcCD/2). Пусть arcAB=2a,arcCD=2c, a+c=60°.
    # p=2R sin a, q=2R sin c. Найдём R с a+c=60.
    def eqs(v):
        R, a = v
        c = math.radians(60) - a
        return [2 * R * math.sin(a) - p, 2 * R * math.sin(c) - q]
    R, a = newton(eqs, [max(p, q), math.radians(30)])
    return R

