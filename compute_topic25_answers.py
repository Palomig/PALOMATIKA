# СЕРИЯ 12 (67–72). Остроугольный △ABC, на BC как на диаметре построена
# полуокружность, пересекает высоту AD в M. AD,MD заданы. H — ортоцентр. Найдите AH.
# M на окружности с диаметром BC => BM⟂MC; MD⟂BC (M на высоте AD, AD⟂BC).
# DM²=BD·DC (высота в прямоуг.). Также для ортоцентра: AH·HD'?; известно AH=AD-2·OH?...
# Классика: DM²=BD·DC, и HD=BD·DC/AD = DM²/AD. AH=AD-HD=AD - DM²/AD.
# ══════════════════════════════════════════════════════════════════════════
def s12(AD, MD):
    HD = MD**2 / AD
    AH = AD - HD
    return AH

