# СЕРИЯ 15 (85–90). Точки M,N на стороне AC на расстояниях am,an от A. Окружность
# через M,N касается луча AB. cos(BAC)=cs. Найдите радиус.
# Касательная из A: AM·AN=AT² (степень точки) => AT=sqrt(am·an). Окружность через
# M,N касается AB в T, AT=sqrt(am·an). Радиус: R=MN/(2 sin∠MTN)? Используем модель.
# ══════════════════════════════════════════════════════════════════════════
def s15(am, an, cosA):
    AT = math.sqrt(am * an)
    A = np.array([0.0, 0.0])
    # AC вдоль направления угла A от AB. AB вдоль оси x. угол A: cosA.
    angA = math.acos(cosA)
    dirAC = np.array([math.cos(angA), math.sin(angA)])
    M = am * dirAC; N = an * dirAC
    T = np.array([AT, 0.0])  # на луче AB (ось x)
    # окружность через M,N,T

    def circ(P, Q, Rr):
        ax, ay = P; bx, by = Q; cx, cy = Rr
        d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
        ux = ((ax**2 + ay**2) * (by - cy) + (bx**2 + by**2) * (cy - ay) + (cx**2 + cy**2) * (ay - by)) / d
        uy = ((ax**2 + ay**2) * (cx - bx) + (bx**2 + by**2) * (ax - cx) + (cx**2 + cy**2) * (bx - ax)) / d
        return np.array([ux, uy])
    O = circ(M, N, T)
    R = np.linalg.norm(O - T)
    # verify tangent: O-T ⟂ AB(ось x) => O_x==T_x
    assert abs(O[0] - T[0]) < 1e-6, (am, an, cosA, O, T)
    return R

