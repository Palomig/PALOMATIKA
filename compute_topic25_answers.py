# СЕРИЯ 6 (31–36). Треугольник ABC: биссектриса BE и медиана AD перпендикулярны
# и равны L. Найдите стороны.
# Классика: в △ABD BO — биссектриса и высота => AB=BD=BC/2 => BC=2·AB.
# Найдём через модель. Cross-check со Школково: L=24.
# ══════════════════════════════════════════════════════════════════════════
def s6(L):
    # Неизвестные: положим B=(0,0). Пусть AB=c. BC=2c (док-во). Угол ABC=2φ (бис. делит).
    # A=(c cosφ_?,...). Поставим биссектрису BE вдоль оси x (B=(0,0), E на оси x).
    # Тогда лучи BA и BC симметричны относительно оси x под углом ±φ.
    # A = c*(cosφ, sinφ); C = 2c*(cosφ, -sinφ).  D=mid(BC)=c*(cosφ,-sinφ).
    # AD ⟂ BE(ось x) => AD вертикально => A_x = D_x => c cosφ = c cosφ  (всегда!). Хорошо,
    # значит A_x=D_x автоматически, AD вертикальный. Длина AD=|A_y-D_y|=c sinφ-(-c sinφ)=2c sinφ.
    # BE: E на AC, BE вдоль оси x => E=(e,0). |BE|=e=L. AD=2c sinφ=L.
    # E=пересечение AC с осью x. A=(c cosφ,c sinφ), C=(2c cosφ,-2c sinφ).
    # параметр: P=A+u(C-A), Py=0 => c sinφ+u(-2c sinφ-c sinφ)=0 => u=1/3. E_x=A_x+ (1/3)(C_x-A_x)
    # =c cosφ+(1/3)(2c cosφ-c cosφ)=c cosφ+(1/3)(c cosφ)=(4/3)c cosφ. => BE=(4/3)c cosφ=L.
    # Система: 2c sinφ=L ; (4/3)c cosφ=L.
    def eqs(v):
        c, phi = v
        return [2 * c * math.sin(phi) - L, (4.0 / 3.0) * c * math.cos(phi) - L]
    c, phi = newton(eqs, [L, math.radians(40)])
    A = np.array([c * math.cos(phi), c * math.sin(phi)])
    B = np.array([0.0, 0.0])
    C = np.array([2 * c * math.cos(phi), -2 * c * math.sin(phi)])
    AB = np.linalg.norm(A - B)
    BC = np.linalg.norm(B - C)
    AC = np.linalg.norm(A - C)
    # verify perpendicular & equal
    D = (B + C) / 2
    AD = A - D
    BE = np.array([(4.0 / 3.0) * c * math.cos(phi), 0]) - B
    assert abs(np.dot(AD, BE)) < 1e-6
    assert abs(np.linalg.norm(AD) - L) < 1e-6 and abs(np.linalg.norm(BE) - L) < 1e-6
    return sorted([AB, BC, AC])

