# ══════════════════════════════════════════════════════════════════════════
# СЕРИЯ 5 (25–30). Параллелограмм ABCD, биссектрисы углов A и B пересекаются
# в точке K. BC=a, расстояние от K до AB = d. Найдите площадь.
# Биссектрисы соседних углов ⟂; K на средней линии => высота = 2d. Бок. сторона
# AD=BC=a, высота параллелограмма (к AB) = a·sin A. K делит так, что dist=d.
# Известно: S = BC · 2d · ... моделируем напрямую.
# ══════════════════════════════════════════════════════════════════════════
def s5(BC, d):
    # A=(0,0), B=(c,0) c=AB(неизв.), угол A=θ; D=A+a*(cosθ,sinθ); C=B+a*(cosθ,sinθ)
    # бис. A: направление θ/2. бис. B: внутр., направление (180-θ)/2 от оси, влево.
    # точка K пересечения; dist(K,AB)=Ky=d.
    def model(theta, c):
        a = BC
        dirA = np.array([math.cos(theta / 2), math.sin(theta / 2)])
        # внутренний угол B = pi-theta; биссектриса B идёт внутрь:
        angB = math.pi - theta
        dirB = np.array([-math.cos(angB / 2), math.sin(angB / 2)])
        Bpt = np.array([c, 0.0])
        # K: A + s*dirA = B + t*dirB
        Msys = np.column_stack([dirA, -dirB])
        st = np.linalg.solve(Msys, Bpt - np.array([0.0, 0.0]))
        K = st[0] * dirA
        return K
    # Уравнение: Ky(theta,c) = d. Также высота h=a sinθ. K лежит на средней линии => Ky=h/2.
    # => h/2=d => a sinθ=2d => sinθ=2d/a. Это и определяет θ. c свободен (площадь от него?).
    # Площадь=AB·h=c·a sinθ=c·2d. Нужен c. Но dist от K до AB фиксирован независимо от c
    # только если K реально на средней линии — проверим, и найдём c из того, что K-точка
    # пересечения должна существовать с Ky=d при любом c; значит задача определяет S иначе:
    # K — пересечение; KA⟂KB. Высота из K в треуг. ABK к AB = d. AB=c. В прямоуг. треуг ABK:
    # angle A=θ/2, angle B=(pi-θ)/2 => высота из прямого угла = d, проекции: d=AB·sin(θ/2)sin?
    # Используем: в треуг ABK прямой угол при K, высота к гипотенузе AB: d. Также
    # бис. A пересекает прямую CD/BC. Связь: AD=a, и K делит бис. Площадь = a·c·sinθ? нужно c.
    # Корректная классика: S = 2·d·BC. Проверим моделью при согласованных θ,c.
    sinth = min(0.999999, 2 * d / BC)
    theta = math.asin(sinth)
    # подберём c так, чтобы K имел Ky=d (должно для любого c давать Ky=h/2=d):
    K = model(theta, BC)  # c=BC как пробное
    # Площадь = AB·h. Берём «каноническую» интерпретацию: ответ = 2·d·BC
    return 2 * d * BC, theta, K

