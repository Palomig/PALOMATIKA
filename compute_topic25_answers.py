# ══════════════════════════════════════════════════════════════════════════
# СЕРИЯ 10 (55–60). Окружности радиусов r1,r2 касаются внешне. A,B на первой,
# C,D на второй. AC и BD — общие касательные. Расстояние между прямыми AB и CD.
# Классика: AB и CD — хорды, расстояние = 2·r1·r2/(... ). Считаем моделью.
# Ответ = 4 r1 r2 /(r1+r2)? Проверим.
# ══════════════════════════════════════════════════════════════════════════
def s10(r1, r2):
    # Внешнее касание: центры O1=(0,0),O2=(r1+r2,0), точка касания T=(r1,0).
    # Общие внешние касательные AC и BD (A,B на окр1; C,D на окр2), симметричны отн. оси x.
    # Для внешней касательной к двум окружностям точки касания: угол наклона sinθ=(r1-r2)/d?
    # внешняя касательная: радиусы параллельны. A=O1+r1*n, C=O2+r2*n (один и тот же n⟂касат).
    # n=(sinφ? ) Решим: касательная линия, расстояние от O1=r1, от O2=r2, с одной стороны.
    d = r1 + r2
    # внешняя касательная сверху: нормаль n=(nx,ny). line: n·x = c. n·O1 - c = -r1? возьмём
    # n·O1 - c = r1, n·O2 - c = r2 (обе по одну сторону). Вычтем: n·(O2-O1)=r2-r1 => nx*d=r2-r1
    nx = (r2 - r1) / d
    ny = math.sqrt(1 - nx**2)
    n = np.array([nx, ny])
    O1 = np.array([0.0, 0.0]); O2 = np.array([d, 0.0])
    c = n @ O1 - r1
    A = O1 + r1 * n        # точка касания на окр1 (верх)
    C = O2 + r2 * n        # точка касания на окр2 (верх)
    # нижняя касательная симметрична: B,D — зеркало по оси x
    B = np.array([A[0], -A[1]])
    Dp = np.array([C[0], -C[1]])
    # AB — вертикальная хорда окр1 (x=A[0]); CD — вертикальная хорда окр2 (x=C[0])
    dist = abs(C[0] - A[0])
    return dist

