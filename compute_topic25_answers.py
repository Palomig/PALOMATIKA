# ══════════════════════════════════════════════════════════════════════════
# СЕРИЯ 2 (7–12). Углы при основании трапеции α, β (α+β=90°). Отрезки,
# соединяющие середины противоположных сторон, равны s1 и s2. Найдите основания.
# Средняя линия (между боковыми) = (a+b)/2; отрезок между серединами оснований
# при α+β=90° = (a-b)/2. => a=max+min, b=max-min.
# ══════════════════════════════════════════════════════════════════════════
def s2(a_ang, b_ang, p, q):
    assert abs(a_ang + b_ang - 90) < 1e-9
    M, N = max(p, q), min(p, q)
    a, b = M + N, M - N  # большее, меньшее основание
    # модель-проверка: трапеция с основаниями a (низ) и b (верх), углы α,β при низе
    A = np.array([0.0, 0.0])
    D = np.array([a, 0.0])
    ar = math.radians(a_ang); br = math.radians(b_ang)
    # боковые из A (угол α) и из D (угол β), пересекаются на высоте h, верх = b
    # B = A + tA*(cosα,sinα); C = D + tD*(-cosβ,sinβ); By=Cy=h; Cx-Bx=b
    # tA sinα = tD sinβ = h ; (a - tD cosβ) - (tA cosα) = b
    def eqs(v):
        tA, tD, h = v
        Bx = tA * math.cos(ar); By = tA * math.sin(ar)
        Cx = a - tD * math.cos(br); Cy = tD * math.sin(br)
        return [By - h, Cy - h, (Cx - Bx) - b]
    tA, tD, h = newton(eqs, [a, a, a / 2])
    B = np.array([tA * math.cos(ar), tA * math.sin(ar)])
    C = np.array([a - tD * math.cos(br), tD * math.sin(br)])
    midBC = (B + C) / 2          # середина верхнего основания
    midAD = (A + D) / 2          # середина нижнего основания
    midAB = (A + B) / 2; midCD = (C + D) / 2
    seg_bases = np.linalg.norm(midBC - midAD)   # между серединами оснований
    seg_legs = np.linalg.norm(midCD - midAB)    # средняя линия
    assert abs(seg_legs - M) < 1e-6 and abs(seg_bases - N) < 1e-6, \
        (a_ang, b_ang, p, q, seg_legs, seg_bases, M, N)
    return a, b

