# ══════════════════════════════════════════════════════════════════════════
# СЕРИЯ 4 (19–24). Параллелограмм ABCD, диагональ AC. O — центр вписанной
# окружности △ABC. Расстояния O до A, до прямой AD и до AC = m, n, k.
# Найдите площадь параллелограмма (= 2·[ABC]).
# A=(0,0), AB по оси x. O на биссектрисе угла A: O=(m cosA/2, m sinA/2),
# r=k=m sinA/2 (расст. до AB). AD под углом (A+C). n=m sin(A/2+C).
# ══════════════════════════════════════════════════════════════════════════
def s4(m, n, k):
    A2 = math.asin(k / m)            # A/2
    C = math.asin(n / m) - A2        # угол C
    A = 2 * A2
    Cc = C
    B = math.pi - A - Cc
    r = k
    R = r / (4 * math.sin(A / 2) * math.sin(B / 2) * math.sin(Cc / 2))
    area_tri = 2 * R**2 * math.sin(A) * math.sin(B) * math.sin(Cc)
    # ── самопроверка: строим △ABC, инцентр O, замеряем m,n,k и площадь ──
    a_side = 2 * R * math.sin(A)   # BC
    b_side = 2 * R * math.sin(B)   # CA
    c_side = 2 * R * math.sin(Cc)  # AB
    Av = np.array([0.0, 0.0])
    Bv = np.array([c_side, 0.0])                                   # AB по оси x
    Cv = np.array([b_side * math.cos(A), b_side * math.sin(A)])    # CA под углом A
    O = (a_side * Av + b_side * Bv + c_side * Cv) / (a_side + b_side + c_side)  # инцентр
    # AD ∥ BC, через A: направление BC = Cv-Bv
    dirAD = Cv - Bv; nAD = np.array([-dirAD[1], dirAD[0]]); nAD = nAD / np.linalg.norm(nAD)
    dist_AD = abs((O - Av) @ nAD)
    dirAC = Cv - Av; nAC = np.array([-dirAC[1], dirAC[0]]); nAC = nAC / np.linalg.norm(nAC)
    dist_AC = abs((O - Av) @ nAC)
    OA = np.linalg.norm(O - Av)
    assert abs(OA - m) < 1e-4 and abs(dist_AC - k) < 1e-4 and abs(dist_AD - n) < 1e-4, \
        (m, n, k, OA, dist_AD, dist_AC)
    area_shoelace = abs(np.cross(Bv - Av, Cv - Av)) / 2
    assert abs(area_shoelace - area_tri) < 1e-4
    return 2 * area_tri

