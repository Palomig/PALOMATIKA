# СЕРИЯ 1 (1–6). Трапеция ABCD, боковые AB и CD, основание BC. Биссектриса
# угла ADC проходит через середину AB. Найдите площадь.
# Теорема: S = AB·CD/2 (BC — отвлекающий параметр). Проверяем моделью.
# ══════════════════════════════════════════════════════════════════════════
def s1(AB, CD, BC):
    # модель: A=(0,0), D=(d,0); B=(bx,h), C=(bx+BC,h); M=mid(AB)
    def eqs(v):
        bx, h, d = v
        DA = np.array([-1.0, 0.0])
        DC = np.array([bx + BC - d, h]); DC = DC / np.linalg.norm(DC)
        bis = DA + DC
        M = np.array([bx / 2 - d, h / 2])  # из D
        return [bx**2 + h**2 - AB**2,
                (d - (bx + BC))**2 + h**2 - CD**2,
                bis[0] * M[1] - bis[1] * M[0]]
    bx, h, d = newton(eqs, [1, max(AB, CD), AB + CD])
    area = (BC + d) / 2 * h
    assert abs(area - AB * CD / 2) < 1e-6, (AB, CD, BC, area)
    return area

