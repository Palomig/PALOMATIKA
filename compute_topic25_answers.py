# СЕРИЯ 3 (13–18). Равнобедренная трапеция, в неё можно вписать окружность,
# периметр P, площадь S. Найдите расстояние от точки пересечения диагоналей
# до меньшего основания.
# Вписанная: a+b = 2·боковая => P=2(a+b) => a+b=P/2; боковая=P/4.
# h=2S/(a+b)=4S/P. (q-p)/2=sqrt(боковая²-h²). dist = h·p/(a+b) (p — меньшее).
# ══════════════════════════════════════════════════════════════════════════
def s3(P, S):
    half = P / 4.0           # боковая сторона = (a+b)/2
    h = 4 * S / P
    halfdiff = math.sqrt(half**2 - h**2)   # (q-p)/2
    p = half - halfdiff      # меньшее основание
    q = half + halfdiff      # большее основание
    dist = h * p / (p + q)   # до меньшего (верхнего) основания
    return dist

