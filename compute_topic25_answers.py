# СЕРИЯ 7 (37–42). △ABC: биссектриса угла A делит высоту из B в отношении t1:t2
# (от B). Найдите радиус описанной окружности, BC=a.
# ══════════════════════════════════════════════════════════════════════════
def s7(t1, t2, a):
    # Высота BH из B на AC. Биссектриса AL угла A пересекает BH в точке P, BP:PH=t1:t2.
    # Модель: A=(0,0), AC по оси x, C=(b,0) (b=AC неизв.). B=(Bx,By).
    # H=проекция B на AC=(Bx,0). Биссектриса угла A: вдоль направления (cos(α/2),sin(α/2)),
    # где α=угол при A. P на BH (x=Bx): P=(Bx, yP). P на биссектрисе: yP/Bx? нет, бис из A:
    # точка (Bx, Bx*tan(α/2)). BP:PH=t1:t2 от B(верх) к H(низ, y=0):
    # yP = By*t2/(t1+t2). И yP=Bx*tan(α/2). α=угол между AB и AC(ось x): tanα=By/Bx.
    # Неизв: Bx,By,b. Условия: BC=a => (Bx-b)^2+By^2=a^2. И bis-условие. Третье: ?
    # R=a/(2 sinα). Нужен α. Из bis: Bx tan(α/2)=By t2/(t1+t2); tanα=By/Bx.
    # Пусть tanα=By/Bx=:m. tan(α/2)=（sqrt(1+m^2)-1)/m. Тогда Bx*tan(α/2)=By*t2/(t1+t2)
    # => Bx*(sqrt(1+m^2)-1)/m = (m Bx)*t2/(t1+t2) => (sqrt(1+m^2)-1)/m = m t2/(t1+t2)
    # => sqrt(1+m^2)-1 = m^2 t2/(t1+t2). Решаем относительно m^2.
    k = t2 / (t1 + t2)
    # sqrt(1+x)-1 = x*k, x=m^2 => sqrt(1+x)=1+kx => 1+x=1+2kx+k^2 x^2 => x=2k x+k^2 x^2
    # => 1=2k+k^2 x => x=(1-2k)/k^2
    x = (1 - 2 * k) / k**2
    m2 = x
    sinA = math.sqrt(m2 / (1 + m2))  # sinα = m/sqrt(1+m^2)
    R = a / (2 * sinA)
    return R

