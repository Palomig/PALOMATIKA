# ══════════════════════════════════════════════════════════════════════════
# СЕРИЯ 8 (43–48). Трапеция ABCD, основания AD и BC, сумма углов при AD =90°.
# Найдите радиус окружности через A,B касающейся прямой CD, AB задано.
# При сумме углов 90° боковые AB и CD при продолжении пересекаются под прямым.
# Известный результат: R = AB/2 · AD/(AD-BC)? Проверим моделью.
# ══════════════════════════════════════════════════════════════════════════
def s8(AD, BC, AB):
    # Углы при A и D в сумме 90°. Продолжения AB и DC встречаются в P под прямым углом.
    # Треуг APD прямоуг. с гипотенузой AD. BC ∥ AD отсекает подобный PBC~PAD, k=BC/AD.
    # PA*(1-k)=AB => PA=AB*AD/(AD-BC). Угол α=angle PAD определён: cosα=PA/AD.
    # Координаты: P=начало координат (прямой угол), PA вдоль оси x (A,B на оси x),
    # прямая CD вдоль оси y. A=(PA,0), B=(PB,0). Окружность через A,B касается оси y
    # в T=(0,t): центр O=(R,t). OA=OB=R => вычитание даёт -2R(PA-PB)+(PA²-PB²)=0
    # => R=(PA+PB)/2. Не зависит от t — единственная корректная окружность.
    PA = AB * AD / (AD - BC)
    PB = PA - AB
    R = (PA + PB) / 2
    # численная самопроверка построением
    A = np.array([PA, 0.0]); B = np.array([PB, 0.0])
    t2 = (PA + PB) * 0  # t свободен; берём t из OB: t²=R²-(R-PB)²=2R·PB-PB²
    t = math.sqrt(2 * R * PB - PB**2)
    O = np.array([R, t])
    assert abs(np.linalg.norm(O - A) - R) < 1e-6 and abs(np.linalg.norm(O - B) - R) < 1e-6
    assert abs(O[0] - R) < 1e-9  # касание оси y (прямой CD)
    return R

