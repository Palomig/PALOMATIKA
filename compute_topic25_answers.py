# СЕРИЯ 11 (61–66). △ABC, AB=c, AC=b, O — центр описанной. Прямая BD⟂AO
# пересекает AC в D. Найдите CD.
# AO — радиус к ... ⟂ из B. Известно: BD⟂AO. Касательная в A ⟂ AO. BD∥касательной в A.
# => угол(DBA)=угол между AB и касательной=угол ACB (вписанный). => треуг ABD ~ ...
# Результат: AD=AB²/AC? Тогда CD=AC-AD=b - c²/b. Проверим моделью.
# ══════════════════════════════════════════════════════════════════════════
def s11(c, b):  # c=AB, b=AC
    # модель: окружность, A,B,C на ней. Возьмём конкретный треугольник с AB=c,AC=b и
    # произвольным BC, посчитаем CD, проверим независимость от BC на 2 значениях.
    def cd_for(BC):
        # построим A=(0,0). Поместим так, чтобы было удобно. Зададим углы.
        # Координаты: A=(0,0), C=(b,0). B где-то: AB=c, BC=BC.
        # B: x^2+y^2=c^2; (x-b)^2+y^2=BC^2 => x=(c^2-BC^2+b^2)/(2b)
        x = (c**2 - BC**2 + b**2) / (2 * b)
        y2 = c**2 - x**2
        if y2 <= 0:
            return None
        y = math.sqrt(y2)
        A = np.array([0.0, 0.0]); C = np.array([b, 0.0]); B = np.array([x, y])
        # центр описанной O
        def circ(P, Q, Rr):
            ax, ay = P; bx, by = Q; cx, cy = Rr
            d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
            ux = ((ax**2 + ay**2) * (by - cy) + (bx**2 + by**2) * (cy - ay) + (cx**2 + cy**2) * (ay - by)) / d
            uy = ((ax**2 + ay**2) * (cx - bx) + (bx**2 + by**2) * (ax - cx) + (cx**2 + cy**2) * (bx - ax)) / d
            return np.array([ux, uy])
        O = circ(A, B, C)
        AO = O - A
        # прямая через B ⟂ AO: направление перпендикуляр к AO
        perp = np.array([-AO[1], AO[0]])
        # пересечение с AC (ось x, y=0): B + s*perp, y=0 => s=-B[1]/perp[1]
        if abs(perp[1]) < 1e-12:
            return None
        s = -B[1] / perp[1]
        Dx = B[0] + s * perp[0]
        D = np.array([Dx, 0.0])
        CD = abs(b - Dx)
        return CD
    vals = [cd_for(bc) for bc in [b * 0.7 + c * 0.3 + 1, b * 0.5 + c * 0.5 + 2, abs(b - c) + 3]]
    vals = [v for v in vals if v is not None]
    assert max(vals) - min(vals) < 1e-4, (c, b, vals)
    return vals[0]

