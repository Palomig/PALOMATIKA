# ──────────────────────────────────────────────────────────────────────────
# Универсальный Newton для систем f(x)=0 (численный якобиан). scipy недоступен.
# ──────────────────────────────────────────────────────────────────────────
def newton(f, x0, tol=1e-12, iters=200):
    x = np.array(x0, dtype=float)
    n = len(x)
    for _ in range(iters):
        fx = np.array(f(x), dtype=float)
        if np.max(np.abs(fx)) < tol:
            return x
        J = np.zeros((n, n))
        for j in range(n):
            dx = max(1e-8, abs(x[j]) * 1e-8)
            xp = x.copy(); xp[j] += dx
            J[:, j] = (np.array(f(xp), dtype=float) - fx) / dx
        try:
            step = np.linalg.solve(J, fx)
        except np.linalg.LinAlgError:
            step = np.linalg.lstsq(J, fx, rcond=None)[0]
        # демпфирование
        lam = 1.0
        for _ in range(40):
            xn = x - lam * step
            if np.max(np.abs(np.array(f(xn), dtype=float))) < np.max(np.abs(fx)):
                break
            lam *= 0.5
        x = x - lam * step
    return x


def fmt(v):
    """Числовой ответ -> строка ОГЭ-формата (целое без .0, иначе короткий десятичный)."""
    r = round(v, 6)
    if abs(r - round(r)) < 1e-9:
        return str(int(round(r)))
    s = f"{r:.6f}".rstrip("0").rstrip(".")
    return s


