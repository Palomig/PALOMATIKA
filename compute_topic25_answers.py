# СЕРИЯ 13 (73–78). Середина M стороны AD выпуклого четырёхугольника ABCD
# равноудалена от всех вершин. Найдите AD, если BC=b, углы B и C заданы.
# M равноудалена от всех => A,B,C,D на окружности с центром M, радиус=AD/2,
# AD — диаметр. => углы ABD=ACD=90? Углы B,C даны как углы четырёхугольника.
# AD=диаметр R2=AD. BC=хорда. Найдём AD.
# ══════════════════════════════════════════════════════════════════════════
def s13(b, angB, angC):
    # Окружность радиуса r=AD/2, центр M=(0,0). A=(-r,0),D=(r,0) (AD диаметр).
    # B,C на окружности сверху. Угол ABC=angB, угол BCD=angC. BC=b.
    # Параметризуем B=r(cosβ,sinβ),C=r(cosγ,sinγ). Условия: угол при B (между BA,BC)=angB,
    # угол при C (между CB,CD)=angC, |BC|=b. Неизв: r,β,γ.
    A = lambda r: np.array([-r, 0.0]); D = lambda r: np.array([r, 0.0])

    def eqs(v):
        r, beta, gamma = v
        B = np.array([r * math.cos(beta), r * math.sin(beta)])
        C = np.array([r * math.cos(gamma), r * math.sin(gamma)])
        Av = A(r); Dv = D(r)
        # угол при B между BA и BC
        u = Av - B; w = C - B
        angb = math.degrees(math.acos(np.clip(u @ w / (np.linalg.norm(u) * np.linalg.norm(w)), -1, 1)))
        u2 = B - C; w2 = Dv - C
        angc = math.degrees(math.acos(np.clip(u2 @ w2 / (np.linalg.norm(u2) * np.linalg.norm(w2)), -1, 1)))
        return [angb - angB, angc - angC, np.linalg.norm(C - B) - b]
    r, beta, gamma = newton(eqs, [b, math.radians(120), math.radians(60)])
    # самопроверка резидуалов + выпуклость/порядок A,B,C,D против часовой
    res = eqs([r, beta, gamma])
    assert max(abs(x) for x in res) < 1e-6, (b, angB, angC, res)
    assert 0 < gamma < beta < math.pi, (b, angB, angC, math.degrees(beta), math.degrees(gamma))
    return 2 * r

