# ══════════════════════════════════════════════════════════════════════════
# СЕРИЯ 9 (49–54). Трапеция ABCD, боковая AB⟂основанию BC. Окружность через
# C,D касается AB в точке E. Найдите расстояние от E до CD. AD,BC заданы.
# ══════════════════════════════════════════════════════════════════════════
def s9(AD, BC):
    # AB⟂BC. Поставим B=(0,0), BC по оси x: C=(BC,0). AB по оси y: A=(0,hh) hh=AB(неизв).
    # AD основание, параллельно BC? Основания трапеции AD и BC. BC по оси x =>
    # AD ∥ BC => D=(dx, hh). AD длина => dx=AD (D=(AD,hh)) (A=(0,hh)). hh свободна? нет:
    # ABCD трапеция, порядок вершин A(0,hh)->B(0,0)->C(BC,0)->D(AD,hh). Боковые AB,CD.
    # AB вертикальна. Высота=hh. Окружность через C,D касается AB(ось x=0) в E=(0,ey).
    # Касание оси y => центр O=(R,oy)|? касается x=0 => |ox|=R, ox=R. E=(0,oy).
    # через C=(BC,0),D=(AD,hh): |O-C|=|O-D|=R.
    # dist E до CD ; но hh неизвестна — должно сократиться. Проверим на 2 hh.
    def dist_for(hh):
        Bp = np.array([0.0, 0.0]); C = np.array([BC, 0.0])
        A = np.array([0.0, hh]); D = np.array([AD, hh])

        def eqs(v):
            ox, oy, R = v
            return [ox - R,  # касание оси x=0, центр справа
                    (ox - C[0])**2 + (oy - C[1])**2 - R**2,
                    (ox - D[0])**2 + (oy - D[1])**2 - R**2]
        ox, oy, R = newton(eqs, [BC, hh / 2, BC])
        E = np.array([0.0, oy])
        dirCD = D - C; nrm = np.array([-dirCD[1], dirCD[0]]); nrm = nrm / np.linalg.norm(nrm)
        dist = abs((E - C) @ nrm)
        return dist
    d1 = dist_for(5.0); d2 = dist_for(9.0)
    assert abs(d1 - d2) < 1e-4, (AD, BC, d1, d2)
    return d1

