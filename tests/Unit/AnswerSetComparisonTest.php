<?php

namespace Tests\Unit;

use App\Services\MathAnswerParser;
use App\Services\TaskAnswerResolver;
use PHPUnit\Framework\TestCase;

/**
 * Ответы-множества и промежутки сверяются по смыслу, а не по строке.
 *
 * До этого численная сверка включалась только при наличии радикала, и одна
 * и та же по сути задача вела себя по-разному: «4−√7; 4+√7» принимался в
 * любом порядке, а «−4; −3; 3» из соседнего варианта — только в том порядке,
 * в каком записан в банке. Порядок корней на экзамене не важен, поэтому
 * признаком численной сверки стала форма ответа, а не наличие корня.
 */
class AnswerSetComparisonTest extends TestCase
{
    private TaskAnswerResolver $resolver;

    protected function setUp(): void
    {
        parent::setUp();
        $this->resolver = new TaskAnswerResolver(new MathAnswerParser());
    }

    /**
     * @dataProvider setAnswers
     */
    public function test_answers(string $expected, string $user, bool $want): void
    {
        $this->assertSame(
            $want,
            $this->resolver->isCorrect($user, $expected),
            "«{$user}» ↔ «{$expected}»"
        );
    }

    /** @return array<string, array{0:string,1:string,2:bool}> */
    public static function setAnswers(): array
    {
        return [
            // Порядок корней (тема 20 «Решите уравнение», тема 22, тема 23)
            'корни в другом порядке' => ['-4;-3;3', '3;-3;-4', true],
            'корни с пробелами' => ['-4;-3;3', '-4; -3; 3', true],
            'потерян корень' => ['-4;-3;3', '-4;-3', false],
            'лишний корень' => ['-4;-3', '-4;-3;3', false],
            'другой корень' => ['-4;-3;3', '-4;-3;4', false],
            'значения m в другом порядке' => ['-0,25;0', '0;-0,25', true],
            'точка вместо запятой' => ['-0,25;0', '0;-0.25', true],
            'дроби в другом порядке' => ['-1/6;1/2', '1/2;-1/6', true],
            'дробь и её десятичная запись' => ['-1/6;1/2', '-1/6;0,5', true],
            'углы в другом порядке' => ['60;120', '120;60', true],
            'углы со значком градуса' => ['60;120', '60°;120°', true],
            'корни-радикалы в другом порядке' => [
                '10√13;30√5;20√13', '20√13;10√13;30√5', true,
            ],

            // Объединения промежутков (тема 20 «Решите неравенство», тема 22)
            'объединение в другом порядке' => ['[-6;-4]∪[3;5]', '[3;5]∪[-6;-4]', true],
            'латинская U вместо ∪' => ['[-6;-4]∪[3;5]', '[-6; -4] U [3; 5]', true],
            'другой тип скобки' => ['[-6;-4]∪[3;5]', '[-6;-4]∪[3;5)', false],
            'потеряны границы' => ['[-6;-4]∪[3;5]', '(-6;-4)∪(3;5)', false],
            'изолированная точка в другом порядке' => ['(-∞;-5]∪{4}', '{4}∪(-∞;-5]', true],
            'точка без фигурных скобок' => ['(-∞;-5]∪{4}', '(-∞;-5]∪4', true],
            'потеряна изолированная точка' => ['[-5;1]∪{3}', '[-5;1]', false],
            'множество слева' => ['{-2}∪(-1;6)', '(-1;6)∪{-2}', true],

            // Приближение вместо точного ответа не принимается
            'десятичное приближение радикалов' => [
                '10√13;30√5;20√13', '36,06;67,08;72,11', false,
            ],
            'приближение границ промежутка' => ['(3-√5;3+√5)', '(0,76;5,24)', false],

            // Первая часть: поведение не должно измениться
            'целое число' => ['116', '116', true],
            'целое с пробелами' => ['116', ' 116 ', true],
            'другое целое' => ['116', '117', false],
            'цепочка цифр соответствия' => ['312', '312', true],
            'цепочка цифр в другом порядке' => ['312', '321', false],
            'десятичная дробь' => ['0,5', '0.5', true],
            'обыкновенная дробь вместо десятичной' => ['0,5', '1/2', true],
        ];
    }

    public function test_bare_list_is_not_an_interval(): void
    {
        // «1; 1+√2» — это два числа, а не промежуток «(1; 1+√2)».
        // Иначе ответ без скобок молча засчитался бы за промежуток.
        $parser = new MathAnswerParser();
        $this->assertNull($parser->answersMatch('(1; 1 + \sqrt{2})', '1; 1+√2'));
    }

    public function test_needs_numeric_comparison_ignores_plain_answers(): void
    {
        $parser = new MathAnswerParser();
        foreach (['116', '312', '0,5', '-25', 'c'] as $plain) {
            $this->assertFalse($parser->needsNumericComparison($plain), $plain);
        }
        foreach (['-4;-3;3', '[-6;-4]∪[3;5]', '(-∞;-5]∪{4}', '12√6'] as $rich) {
            $this->assertTrue($parser->needsNumericComparison($rich), $rich);
        }
    }
}
