def _u(ax, ay, bx, by):
    dx, dy = bx - ax, by - ay
    d = math.hypot(dx, dy) or 1.0
    return dx / d, dy / d


def line(x1, y1, x2, y2, c=SIDE, w=2, dash=False):
    d = ' stroke-dasharray="4 4"' if dash else ''
    return f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{c}" stroke-width="{w}" fill="none"{d}/>'


def circle(cx, cy, r, c=SIDE, w=2):
    return f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" stroke="{c}" stroke-width="{w}" fill="none"/>'


def vtx(x, y, label, dx=-12, dy=5, dot=True, size=14):
    s = f'<circle cx="{x:.1f}" cy="{y:.1f}" r="2.4" fill="{PT}"/>' if dot else ''
    s += f'<text x="{x + dx:.1f}" y="{y + dy:.1f}" font-size="{size}" font-style="italic" fill="{PT}">{label}</text>'
    return s


def lbl(x, y, t, c=KNOWN, size=13, weight="bold"):
    return f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" font-weight="{weight}" fill="{c}">{t}</text>'


def tick(x1, y1, x2, y2, n=1, c=MARK, size=5, gap=4, frac=0.5):
    mx, my = x1 + (x2 - x1) * frac, y1 + (y2 - y1) * frac
    ux, uy = _u(x1, y1, x2, y2)
    px, py = -uy, ux
    out = []
    for i in range(n):
        off = (i - (n - 1) / 2) * gap
        cx, cy = mx + ux * off, my + uy * off
        out.append(f'<line x1="{cx - px * size:.1f}" y1="{cy - py * size:.1f}" x2="{cx + px * size:.1f}" y2="{cy + py * size:.1f}" stroke="{c}" stroke-width="1.5"/>')
    return "".join(out)


def rangle(vx, vy, ax, ay, bx, by, size=11, c=RIGHT):
    uax, uay = _u(vx, vy, ax, ay)
    ubx, uby = _u(vx, vy, bx, by)
    p1 = (vx + uax * size, vy + uay * size)
    p2 = (vx + uax * size + ubx * size, vy + uay * size + uby * size)
    p3 = (vx + ubx * size, vy + uby * size)
    return f'<polyline points="{p1[0]:.1f},{p1[1]:.1f} {p2[0]:.1f},{p2[1]:.1f} {p3[0]:.1f},{p3[1]:.1f}" stroke="{c}" stroke-width="1.4" fill="none"/>'


def arc(vx, vy, ax, ay, bx, by, r=20, c=MARK, n=1, gap=4):
    a1 = math.atan2(ay - vy, ax - vx)
    a2 = math.atan2(by - vy, bx - vx)
    d = a2 - a1
    while d <= -math.pi:
        d += 2 * math.pi
    while d > math.pi:
        d -= 2 * math.pi
    sweep = 1 if d > 0 else 0
    out = []
    for i in range(n):
        rr = r + i * gap
        x1 = vx + rr * math.cos(a1)
        y1 = vy + rr * math.sin(a1)
        x2 = vx + rr * math.cos(a1 + d)
        y2 = vy + rr * math.sin(a1 + d)
        out.append(f'<path d="M {x1:.1f} {y1:.1f} A {rr:.1f} {rr:.1f} 0 0 {sweep} {x2:.1f} {y2:.1f}" stroke="{c}" stroke-width="1.4" fill="none"/>')
    return "".join(out)


